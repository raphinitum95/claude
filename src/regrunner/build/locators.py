"""From an element picked on the live page to a locator a step can keep (Q10, Q11, Q49).  Pure logic: the build session (``session.py``) gives
it what the overlay read from the element, checks each candidate on the live page with the engine's own selector code, and hands the counts back.

Order of preference, most stable first:

1. ``id``                        - when it does not look generated (``ember123``, ``react-select-3``, a hash...)
2. a test id                     - ``data-testid`` / ``data-test`` / ``data-qa`` / ``data-cy``...
3. a stable attribute            - ``name``, ``aria-label``, ``placeholder``, ``title``, ``alt``, a plain ``href``
4. its text                      - ``//button[normalize-space(.)='Choose']``, or a field's label
5. its text inside its container - ``//h3[normalize-space(.)='Max']/ancestor::div[...card...][1]//button[normalize-space(.)='Choose']``
6. class + position              - ``button.choose`` + Index (the n-th match), then the element's CSS path

The first candidate that finds exactly the picked element is the step's locator (``FindBy`` / ``FindBy_Value`` / ``Index``); up to three
others that also find it become its ``BACKUP_LOCATORS`` (CONTRACT.md 1.1: on a later break the step still fails, the backups only suggest a fix).

Words: a pick is also described in plain words (``button "Choose" inside card "Max"``).  The name and the container's heading can become a
variable (``{PLAN}``): the locator is then rebuilt from the text forms (4, 5) with ``{PLAN}`` in place of the word, and re-checked live with
the value of each data row.  ``words_of_locator`` reads the same words back from a stored locator, so any step written this way shows them.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from typing import Any, Iterable

from ..selectors.spec import css_string, legacy_strategy, xpath_literal

TEST_ID_ATTRS = ("data-testid", "data-test-id", "data-test", "data-qa", "data-cy", "data-automation-id", "data-automation")
MAX_BACKUPS = 3
MAX_TEXT = 80                                   # longer texts are content, not a name to find an element by

# Plain words for an element's tag / kind (the overlay sends ``kind``; ``words_of_locator`` only has the tag).
KIND_WORDS = {"button": "button", "link": "link", "field": "text field", "textbox": "text box", "dropdown": "dropdown", "checkbox": "checkbox",
              "radio": "option", "image": "image", "heading": "heading", "label": "label", "item": "list item", "cell": "cell", "text": "text",
              "element": "element"}
TAG_KINDS = {"button": "button", "a": "link", "input": "field", "textarea": "textbox", "select": "dropdown", "img": "image", "label": "label",
             "li": "item", "td": "cell", "th": "cell", "h1": "heading", "h2": "heading", "h3": "heading", "h4": "heading", "h5": "heading",
             "h6": "heading", "span": "text", "p": "text", "div": "text", "strong": "text", "b": "text", "em": "text"}
CONTAINER_WORDS = ("card", "row", "item", "form", "dialog", "section", "panel", "box")

_GENERATED_ID = re.compile(r"(\d{3,}|[0-9a-f]{8,}|^(ember|ext-gen|gwt-uid|yui_|j_id|mui-|radix-|headlessui-|react-|__bvid__|:r)|"
                           r"[-_:]\d+$|^[-_:])", re.IGNORECASE)
_GENERATED_CLASS = re.compile(r"(\d{3,}|^css-|^sc-|^jsx-|^_|__[a-z0-9]{5,}$|[0-9a-f]{6,}|^(ng-|is-|has-|js-))", re.IGNORECASE)
_STATE_CLASSES = {"active", "hover", "focus", "focused", "selected", "open", "opened", "closed", "disabled", "enabled", "checked", "visible",
                  "hidden", "show", "shown", "in", "fade", "collapsed", "expanded", "current", "error", "invalid", "valid", "dirty", "touched",
                  "loading", "loaded", "animated", "on", "off"}
TOKEN_IN_TEXT = re.compile(r"\{([A-Za-z_][A-Za-z0-9_]*)\}")


def stable_id(value: str) -> bool:
    """An id (or test id) worth keeping: not generated by a framework, not a hash or a counter that changes with the next build."""
    value = (value or "").strip()
    return bool(value) and len(value) <= 60 and " " not in value and not _GENERATED_ID.search(value)


def stable_classes(classes: Iterable[str]) -> list[str]:
    return [c for c in classes if c and c.lower() not in _STATE_CLASSES and not _GENERATED_CLASS.search(c) and len(c) <= 40][:3]


def short_text(text: str) -> str:
    text = " ".join(str(text or "").split())
    return text if 0 < len(text) <= MAX_TEXT else ""


def lit(text: str) -> str:
    """An XPath string for ``text``; a ``{TOKEN}`` inside stays as written (filled in when the step runs, CONTRACT.md 1.2)."""
    return xpath_literal(text)


@dataclass
class Candidate:
    findby: str                  # BY_ID | BY_CSSSELECTOR | BY_XPATH (the legacy vocabulary: FindBy)
    value: str                   # FindBy_Value
    how: str                     # id | testid | attribute | text | context | anchor | position | path
    index_needed: bool = False   # only finds the element as the n-th match (Index)
    count: int = -1              # filled by the live check: how many elements match
    position: int = -1           # ...and where the picked element is among them (-1: not at all)

    @property
    def unique(self) -> bool:
        return self.count == 1 and self.position == 0

    @property
    def finds_it(self) -> bool:
        return self.position >= 0 and (self.unique or self.index_needed)

    def selector(self, values: dict[str, str] | None = None) -> str:
        """The Playwright selector the engine would use (``selectors.spec.legacy_strategy``), with ``{TOKEN}`` filled in from ``values``."""
        strategy = legacy_strategy(self.findby, fill(self.value, values or {}))
        return strategy.selector if strategy is not None else ""

    def backup(self) -> str:
        """As one ``BACKUP_LOCATORS`` entry (``selectors.spec.parse_locator`` syntax); the n-th match when it needs a position."""
        kind = {"BY_ID": "id", "BY_CSSSELECTOR": "css", "BY_XPATH": "xpath"}[self.findby]
        if self.index_needed and self.position > 0:
            if kind == "xpath":
                return f"xpath=({self.value})[{self.position + 1}]"
            return f"css={self.value} >> nth={self.position}" if kind == "css" else f"css=[id={css_string(self.value)}] >> nth={self.position}"
        return f"{kind}={self.value}"

    def to_json(self) -> dict:
        return {"findBy": self.findby, "value": self.value, "how": self.how, "count": self.count,
                "index": self.position if self.index_needed and self.position >= 0 else 0}


def fill(text: str, values: dict[str, str]) -> str:
    """``{TOKEN}`` -> its value (names compared case-insensitively); unknown names stay as written."""
    upper = {k.upper(): v for k, v in values.items()}
    return TOKEN_IN_TEXT.sub(lambda m: upper.get(m.group(1).upper(), m.group(0)), text)


# -- words ----------------------------------------------------------------------------------------------------------------------------------
def element_name(desc: dict) -> str:
    """What a person would call the element: its label, text, value, placeholder..."""
    for key in ("ariaLabel", "label", "text", "value", "placeholder", "title", "alt"):
        text = short_text(desc.get(key) or "")
        if text:
            return text
    return ""


def descriptive_target(desc: dict) -> str:
    """Words for a step's target that always say *which* element: its name/label/text, else its id or name attribute, else its container's
    heading, else its most telling class (``"Albania" link``, ``first name text field``, ``link in "Flights"``, ``drop screen element``)."""
    kind = kind_word(desc)
    is_field = _is_field(desc)
    text = element_name(desc)
    if text:
        return f"{text.lower()} {kind}" if is_field else f'"{text}" {kind}'
    for key in ("name", "id"):
        value = str(desc.get(key) or "")
        if value and stable_id(value):
            return f"{re.sub(r'[_.-]+', ' ', re.sub(r'(?<=[a-z0-9])(?=[A-Z])', ' ', value)).lower().strip()} {kind}"
    heading = short_text((desc.get("context") or {}).get("heading") or "")
    if heading:
        return f'{kind} in "{heading}"'
    for cls in stable_classes(desc.get("classes") or []):
        return f"{re.sub(r'[_.-]+', ' ', re.sub(r'(?<=[a-z0-9])(?=[A-Z])', ' ', cls)).lower().strip()} {kind}"
    return ""


def kind_word(desc: dict) -> str:
    kind = desc.get("kind") or TAG_KINDS.get(str(desc.get("tag") or "").lower(), "element")
    return KIND_WORDS.get(kind, "element")


def plain_words(desc: dict, variables: dict[str, str] | None = None) -> list[dict]:
    """``[{text, role, variable}]``: ``button`` ``"Choose"`` ``inside card`` ``"Max"`` (CONTRACT.md 2.3 ``locator.plainWords``).  ``role`` is
    ``kind`` / ``name`` / ``context-kind`` / ``context``; only ``name`` and ``context`` can become a variable."""
    variables = variables or {}
    words = [{"text": kind_word(desc), "role": "kind", "variable": ""}]
    name = element_name(desc)
    if name:
        words.append({"text": name, "role": "name", "variable": variables.get("name", "")})
    ctx = desc.get("context") or {}
    heading = short_text(ctx.get("heading") or "")
    if heading and heading != name:
        words.append({"text": f"inside {ctx.get('kind') or 'section'}", "role": "context-kind", "variable": ""})
        words.append({"text": heading, "role": "context", "variable": variables.get("context", "")})
    return words


def describe(words: list[dict]) -> str:
    """``button "Choose" inside card "Max"`` ({PLAN} for a word that is a variable)."""
    out = []
    for w in words:
        if w["role"] in ("name", "context"):
            out.append("{" + w["variable"] + "}" if w.get("variable") else f"“{w['text']}”")
        else:
            out.append(w["text"])
    return " ".join(out)


# -- candidates -----------------------------------------------------------------------------------------------------------------------------
def _attr_css(tag: str, attr: str, value: str) -> str:
    return f"{tag}[{attr}={css_string(value)}]"


def _text_pred(desc: dict, text: str) -> str:
    """The XPath predicate that finds the element by its name ``text``: its own text, or a button input's value."""
    tag = str(desc.get("tag") or "").lower()
    if tag == "input" and (desc.get("type") or "").lower() in ("submit", "button", "reset"):
        return f"[@value={lit(text)}]"
    if desc.get("ariaLabel") and short_text(desc["ariaLabel"]) == text:
        return f"[@aria-label={lit(text)}]"
    return f"[normalize-space(.)={lit(text)}]"


def _inner(desc: dict, name: str) -> str:
    """What finds the element once inside its container: its name, else a stable attribute, else only its tag."""
    tag = str(desc.get("tag") or "*").lower()
    if name and not _is_field(desc):
        return f"{tag}{_text_pred(desc, name)}"
    for attr, key in (("name", "name"), ("aria-label", "ariaLabel"), ("placeholder", "placeholder")):
        value = desc.get(key)
        if value and (attr != "name" or stable_id(value)):
            return f"{tag}[@{attr}={lit(str(value))}]"
    return tag


def _is_field(desc: dict) -> bool:
    return desc.get("kind") in ("field", "textbox", "dropdown", "checkbox", "radio") or str(desc.get("tag") or "").lower() in ("input", "textarea", "select")


def _context_forms(desc: dict, name: str, heading: str) -> list[Candidate]:
    ctx = desc.get("context") or {}
    htag = str(ctx.get("headingTag") or "*").lower()
    ctag = str(ctx.get("tag") or "*").lower()
    inner = _inner(desc, name)
    anchor = f"//{htag}[normalize-space(.)={lit(heading)}]/ancestor::{ctag}"
    out = []
    classes = stable_classes(ctx.get("classes") or [])
    if classes:
        out.append(Candidate("BY_XPATH", f"{anchor}[contains(concat(' ', normalize-space(@class), ' '), {lit(' ' + classes[0] + ' ')})][1]//{inner}", "context"))
    out.append(Candidate("BY_XPATH", f"{anchor}[1]//{inner}", "context"))
    return out


def candidates(desc: dict, *, name_as: str = "", context_as: str = "") -> list[Candidate]:
    """Every locator worth checking for the element, most stable first.  ``name_as`` / ``context_as``: a ``{TOKEN}`` that replaces the
    element's name / its container's heading - then only the forms that carry the word are offered (the locator must follow the variable)."""
    tag = str(desc.get("tag") or "*").lower()
    name = element_name(desc)
    heading = short_text((desc.get("context") or {}).get("heading") or "")
    if heading == name:
        heading = ""
    if name_as or context_as:
        out = []
        use_name = name_as or name
        use_heading = context_as or heading
        if name_as and name:
            out.append(Candidate("BY_XPATH", f"//{tag}{_text_pred(desc, name)}".replace(lit(name), lit(use_name)), "text"))
        if use_heading and (name_as or context_as):
            for c in _context_forms(desc, use_name if name_as else name, use_heading):
                out.append(c)
        return [c for c in out if TOKEN_IN_TEXT.search(c.value)]

    out: list[Candidate] = []
    element_id = str(desc.get("id") or "")
    if stable_id(element_id):
        out.append(Candidate("BY_ID", element_id, "id"))
    testid = desc.get("testid") or {}
    if testid.get("attr") in TEST_ID_ATTRS and stable_id(str(testid.get("value") or "")):
        out.append(Candidate("BY_CSSSELECTOR", f"[{testid['attr']}={css_string(str(testid['value']))}]", "testid"))
    attrs = [("name", desc.get("name"))] if _is_field(desc) or tag == "button" else []
    attrs += [("aria-label", desc.get("ariaLabel")), ("placeholder", desc.get("placeholder")), ("title", desc.get("title")), ("alt", desc.get("alt"))]
    for attr, value in attrs:
        value = str(value or "").strip()
        if value and (attr != "name" or stable_id(value)) and len(value) <= MAX_TEXT:
            css = _attr_css(tag, attr, value)
            if tag == "input" and (desc.get("type") or "").lower() == "radio" and desc.get("value"):
                css += f"[value={css_string(str(desc['value']))}]"
            out.append(Candidate("BY_CSSSELECTOR", css, "attribute"))
    href = str(desc.get("href") or "")
    if tag == "a" and href and "?" not in href and "#" not in href[1:] and len(href) <= 120 and not re.search(r"\d{4,}", href):
        out.append(Candidate("BY_CSSSELECTOR", _attr_css("a", "href", href), "attribute"))
    if name and not _is_field(desc):
        out.append(Candidate("BY_XPATH", f"//{tag}{_text_pred(desc, name)}", "text"))
    label = short_text(desc.get("label") or "")
    if label and _is_field(desc):
        out.append(Candidate("BY_XPATH", f"//label[normalize-space(.)={lit(label)}]/following::{tag}[1]", "text"))
    if heading:
        out.extend(_context_forms(desc, name, heading))
    classes = stable_classes(desc.get("classes") or [])
    if classes:
        out.append(Candidate("BY_CSSSELECTOR", tag + "".join("." + _css_ident(c) for c in classes), "position", index_needed=True))
    anchor = str(desc.get("anchorPath") or "")
    if anchor:
        out.append(Candidate("BY_CSSSELECTOR", anchor, "anchor"))
    out.append(Candidate("BY_CSSSELECTOR", tag, "position", index_needed=True))
    path = str(desc.get("cssPath") or "")
    if path:
        out.append(Candidate("BY_CSSSELECTOR", path, "path"))
    seen: set[tuple[str, str]] = set()
    unique = []
    for c in out:
        if (c.findby, c.value) not in seen:
            seen.add((c.findby, c.value))
            unique.append(c)
    return unique


def _css_ident(name: str) -> str:
    return re.sub(r"([^A-Za-z0-9_-])", r"\\\1", name)


# -- choosing ---------------------------------------------------------------------------------------------------------------------------------
@dataclass
class Choice:
    primary: Candidate | None
    backups: list[Candidate] = field(default_factory=list)
    tried: list[Candidate] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return self.primary is not None

    def to_json(self) -> dict:
        p = self.primary
        return {"findBy": p.findby if p else "", "value": p.value if p else "", "index": (p.position if p and p.index_needed else 0) if p else 0,
                "how": p.how if p else "", "matches": p.count if p else 0, "backups": [b.backup() for b in self.backups],
                "tried": [c.to_json() for c in self.tried]}


def choose(checked: list[Candidate]) -> Choice:
    """Pick the step's locator among candidates already checked live (``count`` / ``position`` set): the most stable one that finds exactly
    the picked element; else the first that finds it as the n-th match.  Up to ``MAX_BACKUPS`` others that find it become its backups."""
    unique = [c for c in checked if c.unique and c.how != "path"]
    positional = [c for c in checked if c.index_needed and c.position >= 0]
    path = [c for c in checked if c.how == "path" and c.unique]
    # a path from the element's own ancestors is specific to it; "the 425th <a> on the page" is not, so it is the last resort
    primary = unique[0] if unique else path[0] if path else positional[0] if positional else None
    rest = [c for c in [*unique, *path, *positional[:1]] if c is not primary]
    return Choice(primary, rest[:MAX_BACKUPS], list(checked))


# -- reading a stored locator back as words -------------------------------------------------------------------------------------------------
_LIT = r"(?:'([^']*)'|\"([^\"]*)\")"
_TEXT_FORM = re.compile(r"^//([A-Za-z0-9*]+)\[(?:normalize-space\(\.\)|@value|@aria-label)=" + _LIT + r"\]$")
_LABEL_FORM = re.compile(r"^//label\[normalize-space\(\.\)=" + _LIT + r"\]/following::([A-Za-z0-9*]+)\[1\]$")
_CONTEXT_FORM = re.compile(r"^//([A-Za-z0-9*]+)\[normalize-space\(\.\)=" + _LIT + r"\]/ancestor::([A-Za-z0-9*]+)(\[contains\([^\]]*\)\])?\[1\]//"
                           r"([A-Za-z0-9*]+)(?:\[(?:normalize-space\(\.\)|@value|@aria-label|@name|@placeholder)=" + _LIT + r"\])?$")


def _word(text: str, role: str) -> dict:
    m = TOKEN_IN_TEXT.fullmatch(text.strip())
    return {"text": text, "role": role, "variable": m.group(1) if m else ""}


def container_word(tag: str, class_pred: str = "") -> str:
    low = (class_pred or "").lower()
    for word in CONTAINER_WORDS:
        if word in low:
            return word
    return {"tr": "row", "li": "item", "form": "form", "dialog": "dialog", "fieldset": "section", "section": "section",
            "article": "card"}.get(tag.lower(), "section")


def words_of_locator(findby: str, value: str) -> list[dict]:
    """The plain words of a locator the builder wrote (text / label / container forms); ``[]`` for any other locator."""
    kind = (findby or "").upper().replace(" ", "")
    value = (value or "").strip()
    if kind not in ("BY_XPATH", "XPATH") or not value:
        return []
    m = _CONTEXT_FORM.match(value)
    if m:
        heading = m.group(2) if m.group(2) is not None else m.group(3)
        ctag, cpred, tag = m.group(4), m.group(5) or "", m.group(6)
        name = m.group(7) if m.group(7) is not None else m.group(8)
        words = [{"text": KIND_WORDS.get(TAG_KINDS.get(tag.lower(), "element"), "element"), "role": "kind", "variable": ""}]
        if name is not None:
            words.append(_word(name, "name"))
        words += [{"text": f"inside {container_word(ctag, cpred)}", "role": "context-kind", "variable": ""}, _word(heading, "context")]
        return words
    m = _TEXT_FORM.match(value)
    if m:
        tag, text = m.group(1), m.group(2) if m.group(2) is not None else m.group(3)
        return [{"text": KIND_WORDS.get(TAG_KINDS.get(tag.lower(), "element"), "element"), "role": "kind", "variable": ""}, _word(text, "name")]
    m = _LABEL_FORM.match(value)
    if m:
        label, tag = (m.group(1) if m.group(1) is not None else m.group(2)), m.group(3)
        return [{"text": KIND_WORDS.get(TAG_KINDS.get(tag.lower(), "field"), "text field"), "role": "kind", "variable": ""}, _word(label, "name")]
    return []


def backups_json(backups: list[str]) -> str:
    return json.dumps(backups)


def to_desc(value: Any) -> dict:
    """What the overlay sent, kept to the keys this module reads (it comes from the page: never trust its shape)."""
    if not isinstance(value, dict):
        return {}
    keep = ("tag", "kind", "id", "name", "type", "testid", "ariaLabel", "placeholder", "title", "alt", "href", "value", "classes", "text",
            "label", "context", "cssPath", "anchorPath", "frame", "current")
    out = {k: value.get(k) for k in keep if k in value}
    for key in ("tag", "kind", "id", "name", "type", "ariaLabel", "placeholder", "title", "alt", "href", "value", "text", "label", "cssPath", "anchorPath", "frame"):
        if key in out:
            out[key] = str(out[key] or "")[:500]
    out["classes"] = [str(c)[:80] for c in (out.get("classes") or [])][:20] if isinstance(out.get("classes"), list) else []
    ctx = out.get("context")
    out["context"] = ({k: (str(ctx.get(k) or "")[:200] if k != "classes" else [str(c)[:80] for c in (ctx.get("classes") or [])][:20])
                       for k in ("kind", "tag", "heading", "headingTag", "id", "classes")} if isinstance(ctx, dict) else None)
    tid = out.get("testid")
    out["testid"] = {"attr": str(tid.get("attr") or ""), "value": str(tid.get("value") or "")[:200]} if isinstance(tid, dict) else None
    cur = out.get("current")
    if isinstance(cur, dict) and str(out.get("type") or "").lower() == "password":
        cur = {**cur, "value": ""}                                  # (a password's value is never kept with a pick)
    out["current"] = ({"value": str(cur.get("value") or "")[:200], "checked": bool(cur.get("checked")), "enabled": cur.get("enabled") is not False,
                       "visible": cur.get("visible") is not False, "selected": str(cur.get("selected") or "")[:200]}
                      if isinstance(cur, dict) else {})
    return out
